#!/usr/bin/env python3
"""poidh #1550 analysis: monthly trends + agent self-ID signals."""
import json, re
from collections import Counter, defaultdict

D = "/home/hatch/workspace/taskmarket/poidh-1550/"
bounties = {}
for line in open(D + "event-scan-bounties-full.jsonl"):
    r = json.loads(line)
    bounties[r["id"]] = r
claims = {}
for line in open(D + "event-scan-claims-full.jsonl"):
    r = json.loads(line)
    if r["id"] == 0:  # empty struct, not a real claim
        continue
    claims[r["id"]] = r

print(f"bounties={len(bounties)} claims={len(claims)} accepted={sum(1 for c in claims.values() if c['accepted'])}")

STRONG = [
    "ai agent", "autonomous agent", "i am an ai", "i'm an ai", "i am an agent",
    "i'm an agent", "built by an agent", "created by an agent", "agent-built",
    "agent built", "claude", "chatgpt", "gpt-4", "gpt-5", "gemini", "copilot",
    "cursor", "Muse", "openclaw", "autogpt", "babyagi", "multi-agent",
    "agent swarm", "as an ai agent", "this agent", "agentic", "ai-powered",
    "ai powered", "by an agent", "autonomous ai", "agent-to-agent",
]
WEAK = [
    " ai ", "artificial intelligence", "llm", " bot ", "bot,", "bot.",
    "automated", "automation", "chatbot", "machine learning",
    "generated by ai", "with ai", "using ai", "ai-generated", "ai assisted",
]

def hits(text, kws):
    t = " " + text.lower() + " "
    return [k for k in kws if k in t]

def analyze(items, label):
    by_month = defaultdict(lambda: {"n": 0, "strong": 0, "weak": 0, "strong_ids": []})
    for r in items:
        m = r["month"]
        by_month[m]["n"] += 1
        text = (r.get("title", "") + " " + r.get("description", "")).lower()
        s = hits(text, STRONG)
        w = hits(text, WEAK)
        if s:
            by_month[m]["strong"] += 1
            by_month[m]["strong_ids"].append((r["id"], s))
        elif w:
            by_month[m]["weak"] += 1
    print(f"\n== {label} ==")
    print(f"{'month':8} {'n':>5} {'strong':>6} {'strong%':>7} {'weak-only':>9}")
    for m in sorted(by_month):
        d = by_month[m]
        print(f"{m:8} {d['n']:>5} {d['strong']:>6} {100*d['strong']/d['n']:>6.1f}% {d['weak']:>9}")
    tot = sum(d["n"] for d in by_month.values())
    ts = sum(d["strong"] for d in by_month.values())
    tw = sum(d["weak"] for d in by_month.values())
    print(f"TOTAL {tot} strong={ts} ({100*ts/tot:.1f}%) weak-only={tw} ({100*tw/tot:.1f}%)")
    return by_month

bm = analyze(list(bounties.values()), "BOUNTIES (title+description)")
cm = analyze(list(claims.values()), "CLAIMS (title+description)")
acc = [c for c in claims.values() if c["accepted"]]
am = analyze(acc, "ACCEPTED CLAIMS")

# strong-hit detail for manual review
print("\n== STRONG bounty hits (id, month, keywords, title) ==")
for m in sorted(bm):
    for cid, kws in bm[m]["strong_ids"]:
        b = bounties[cid]
        print(f"  bounty {cid} {m} {kws} | {b['title'][:90]}")
print("\n== STRONG claim hits: count per month ==")
for m in sorted(cm):
    ids = cm[m]["strong_ids"]
    if ids:
        print(f"  {m}: {len(ids)} claims, e.g. ids {[i for i, _ in ids[:8]]}")
print("\n== STRONG claim keyword frequency ==")
kwc = Counter()
for c in claims.values():
    text = (c.get("title", "") + " " + c.get("description", "")).lower()
    for k in hits(text, STRONG):
        kwc[k] += 1
for k, v in kwc.most_common(20):
    print(f"  {k!r}: {v}")

# issuer clustering
print("\n== top bounty issuers ==")
for a, n in Counter(b["issuer"] for b in bounties.values()).most_common(10):
    print(f"  {a}: {n} bounties")
print("distinct bounty issuers:", len(set(b["issuer"] for b in bounties.values())))
print("\n== top claim issuers ==")
for a, n in Counter(c["issuer"] for c in claims.values()).most_common(10):
    print(f"  {a}: {n} claims")
print("distinct claim issuers:", len(set(c["issuer"] for c in claims.values())))
print("\n== distinct issuers per month (bounties) ==")
for m in sorted(set(b["month"] for b in bounties.values())):
    s = set(b["issuer"] for b in bounties.values() if b["month"] == m)
    print(f"  {m}: {len(s)}")
print("\n== distinct claimants per month ==")
for m in sorted(set(c["month"] for c in claims.values())):
    s = set(c["issuer"] for c in claims.values() if c["month"] == m)
    print(f"  {m}: {len(s)}")

# claims per bounty distribution
per_b = Counter(c["bountyId"] for c in claims.values())
print("\n== claims per bounty: max", max(per_b.values()), "bounties with 0 claims:",
      len([b for b in bounties if per_b.get(b, 0) == 0]),
      "| >10 claims:", sum(1 for v in per_b.values() if v > 10))
# ETH totals
tot_eth = sum(b["amount_eth"] for b in bounties.values())
acc_eth = sum(bounties[c["bountyId"]]["amount_eth"] for c in claims.values() if c["accepted"] and c["bountyId"] in bounties)
print(f"\ntotal bounty value: {tot_eth:.4f} ETH; value of accepted-claim bounties: {acc_eth:.4f} ETH")
print("bounty 564 (#1550):", {k: bounties[564][k] for k in ("id", "issuer", "title", "amount_eth", "claimer", "createdAt", "claimId")})
